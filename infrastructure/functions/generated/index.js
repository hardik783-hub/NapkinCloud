const { randomUUID } = require("crypto");
const { S3Client, PutObjectCommand, ListObjectsV2Command } = require("@aws-sdk/client-s3");
const s3 = new S3Client({});
const { SQSClient, SendMessageCommand } = require("@aws-sdk/client-sqs");
const sqs = new SQSClient({});

exports.handler = async (event) => {
  const corsHeaders = {
    "Access-Control-Allow-Origin": "*",
    "Access-Control-Allow-Headers": "Content-Type,X-Amz-Date,Authorization,X-Api-Key",
    "Access-Control-Allow-Methods": "*"
  };

  const httpMethod = (event.httpMethod || (event.requestContext && event.requestContext.http && event.requestContext.http.method) || "").toUpperCase();

  if (!httpMethod) {
    return {
      statusCode: 400,
      headers: corsHeaders,
      body: JSON.stringify({ success: false, error: "Unsupported event source" })
    };
  }

  if (httpMethod === "OPTIONS") {
    return {
      statusCode: 200,
      headers: corsHeaders,
      body: ""
    };
  }

  try {
    if (httpMethod === "GET") {
      const listResult = await s3.send(
        new ListObjectsV2Command({
          Bucket: process.env.BUCKET_NAME,
          MaxKeys: 50
        })
      );
      return {
        statusCode: 200,
        headers: corsHeaders,
        body: JSON.stringify({
          success: true,
          count: (listResult.Contents || []).length,
          items: listResult.Contents || []
        })
      };
    }


    const body =
      JSON.parse(event.body || "{}");

    // Generated by NapkinCloud
    // Function: UploadFileFunction
    // Logic: Process the incoming request

    const record = {
      ...body,

      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString()
    };

    if (process.env.BUCKET_NAME) {
      await s3.send(
        new PutObjectCommand({
          Bucket: process.env.BUCKET_NAME,
          Key: "uploads/" + (record["id"] || randomUUID()) + ".json",
          Body: JSON.stringify(record),
          ContentType: "application/json"
        })
      );
      record._s3Key = "uploads/" + (record["id"] || randomUUID()) + ".json";
    }

    if (process.env.QUEUE_URL) {
      await sqs.send(
        new SendMessageCommand({
          QueueUrl: process.env.QUEUE_URL,
          MessageBody: JSON.stringify(record)
        })
      );
    }

    return {
      statusCode: 201,
      headers: corsHeaders,
      body: JSON.stringify(record)
    };

  } catch (error) {
    console.error(
      "Lambda execution failed:",
      error
    );

    return {
      statusCode: 500,
      headers: corsHeaders,
      body: JSON.stringify({
        error: error.message || "Internal server error"
      })
    };
  }
};
